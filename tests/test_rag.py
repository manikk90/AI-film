def write(root, rel, text):
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")
    return p


class FixtureRepo(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        write(self.root, "AGENTS.md", AGENTS)
        write(self.root, "studio/LEARNINGS.md", LEARN)
        write(self.root, "studio/README.md", README)
        write(self.root, ".claude/skills/paper-moon/SKILL.md", SKILL)
        write(self.root, "styles/ink-wash/STYLE.md", STYLE)
        write(self.root, "studio/.env", "API_KEY=do-not-index\n")
        write(self.root, "studio/rag_recipes.json", (REPO / "studio" / "rag_recipes.json").read_text())
        for slug, fact in (("film-a", "The fort was built in 1631."), ("film-b", "The river is 300 km long.")):
            write(self.root, f"projects/{slug}/FACTS.md",
                  f"| Claim | Source | Date | Confidence |\n|---|---|---|---|\n| {fact} | https://example.org | "
                  f"2026-11-01 | high |\n")
            write(self.root, f"projects/{slug}/00-brief.md", f"# Brief: {slug}\n\n- Topic: {slug} story\n")
        self.saved = rag.REPO, rag.STUDIO_DB, rag.RECIPES
        rag.REPO, rag.STUDIO_DB, rag.RECIPES = self.root, self.root / ".rag/studio.db", \
            self.root / "studio/rag_recipes.json"
        rag.index(rag.STUDIO_DB, quiet=True)

    def tearDown(self):
        rag.REPO, rag.STUDIO_DB, rag.RECIPES = self.saved
        self.tmp.cleanup()

    def rows(self, sql, *args):
        con = sqlite3.connect(rag.STUDIO_DB)
        try:
            return con.execute(sql, args).fetchall()
        finally:
            con.close()


class ChunkingTest(FixtureRepo):
    def test_citations_point_at_the_cited_lines_and_headings_keep_their_path(self):
        for path, a, b, text in self.rows("SELECT path, line_start, line_end, text FROM chunks WHERE tier != 'P'"):
            lines = (self.root / path).read_text(encoding="utf-8").splitlines()[a - 1:b]
            if path.endswith(".md") and not text.startswith("paper-moon:"):  # summaries are composed, not quoted
                first = text.splitlines()[0]
                self.assertIn(first.strip(), "\n".join(lines), (path, a, b))
        heads = [h for (h,) in self.rows("SELECT heading FROM chunks WHERE path='styles/ink-wash/STYLE.md'")]
        self.assertIn("STYLE.md › Ink wash › Look", heads)
        code = self.rows("SELECT text FROM chunks WHERE text LIKE '%not a heading inside code%'")
        self.assertEqual(len(code), 1)
        self.assertIn("x = 1", code[0][0])  # the fence stayed whole; '#' inside it did not start a section

    def test_tables_stay_whole_and_the_generated_harness_block_is_not_indexed_again(self):
        table = self.rows("SELECT text FROM chunks WHERE text LIKE '%| Layer |%' AND sub != 'summary'")
        self.assertEqual(len(table), 1)
        self.assertIn("| village | near |", table[0][0])
        self.assertFalse(self.rows("SELECT 1 FROM chunks WHERE path LIKE '.claude/skills/%' AND text LIKE "
                                   "'%Studio harness: read this first%'"))

    def test_learnings_are_one_chunk_per_rule_with_date_scope_and_status(self):
        got = self.rows("SELECT line_start, date, scope, status, text FROM chunks WHERE path='studio/LEARNINGS.md' "
                        "AND tier='R1' ORDER BY line_start")
        by_line = {g[0]: g for g in got}
        self.assertEqual(by_line[6][1:4], ("2026-11-01", "global", "current"))
        self.assertEqual(by_line[7][3], "superseded 2026-11-08")
        self.assertIn("Also blocked: example.org", by_line[7][4])  # the indented continuation stays with its rule
        self.assertEqual(by_line[13][2], "director")

    def test_secrets_and_other_films_are_never_in_the_studio_index(self):
        paths = {p for (p,) in self.rows("SELECT DISTINCT path FROM chunks")}
        self.assertNotIn("studio/.env", paths)
        self.assertFalse([p for p in paths if p.startswith("projects/")])


class IndexTest(FixtureRepo):
    def test_only_changed_files_are_rechunked_and_deleted_files_drop_out(self):
        self.assertEqual(rag.index(rag.STUDIO_DB, quiet=True), 0)
        time.sleep(0.01)
        p = self.root / "styles/ink-wash/STYLE.md"
        p.write_text(STYLE.replace("red seal", "blue seal"), encoding="utf-8")
        os.utime(p, None)
        self.assertEqual(rag.index(rag.STUDIO_DB, quiet=True), 1)
        self.assertTrue(self.rows("SELECT 1 FROM fts WHERE fts MATCH 'blue'"))
        self.assertFalse(self.rows("SELECT 1 FROM fts WHERE fts MATCH 'red'"))
        p.unlink()
        self.assertEqual(rag.index(rag.STUDIO_DB, quiet=True), 1)
        self.assertFalse(self.rows("SELECT 1 FROM chunks WHERE path='styles/ink-wash/STYLE.md'"))

    def test_a_same_size_copy_that_keeps_the_mtime_is_still_reindexed(self):
        p = self.root / "styles/ink-wash/STYLE.md"
        st = p.stat()
        p.write_text(STYLE.replace("red seal", "tan seal"), encoding="utf-8")  # same length, same mtime below
        os.utime(p, ns=(st.st_atime_ns, st.st_mtime_ns))
        self.assertEqual(rag.index(rag.STUDIO_DB, quiet=True), 1)
        self.assertTrue(self.rows("SELECT 1 FROM fts WHERE fts MATCH 'tan'"))

    def test_a_file_that_grows_past_the_limit_drops_its_old_chunks(self):
        saved = rag.MAX_BYTES
        try:
            sizes = [f.stat().st_size for f in self.root.rglob("*.md")]
            rag.MAX_BYTES = max(sizes) + 10  # every fixture file still fits ...
            write(self.root, "styles/ink-wash/STYLE.md", STYLE + "x" * rag.MAX_BYTES)  # ... until this one grows
            self.assertEqual(rag.index(rag.STUDIO_DB, quiet=True), 1)
            self.assertFalse(self.rows("SELECT 1 FROM chunks WHERE path='styles/ink-wash/STYLE.md'"))
        finally:
            rag.MAX_BYTES = saved

    def test_query_reindexes_a_file_edited_after_the_index(self):
        write(self.root, "styles/zari/STYLE.md", "# Zari\n\nGold zardozi thread embroidery on velvet.\n")
        blocks, _, _ = rag.query("zardozi embroidery", with_pins=False)
        self.assertEqual(blocks[0]["path"], "styles/zari/STYLE.md")


class QueryTest(FixtureRepo):
    def test_pinned_rules_always_come_first_and_skill_pins_only_for_that_skill(self):
        _, pins, _ = rag.query("ink wash dissolve")
        texts = "\n".join(p["text"] for p in pins)
        self.assertIn("Do not mark a shot accepted", texts)
        self.assertIn("No posting, scheduling or messaging", texts)
        self.assertNotIn("Never use a real logo", texts)
        _, pins, _ = rag.query("ink wash dissolve", skill="paper-moon")
        self.assertIn("Never use a real logo", "\n".join(p["text"] for p in pins))

    def test_newest_owner_rule_is_current_and_older_ones_say_so(self):
        res = rag.rank("deliver finished film 2 files zip")
        by_date = {r["date"]: r["status"] for r in res if r["path"] == "studio/LEARNINGS.md"}
        self.assertEqual(by_date["2026-11-09"], "current")
        self.assertTrue(by_date["2026-11-03"].startswith("older: a newer related rule (2026-11-09"))
        res = rag.rank("elevenlabs blocked cloud")
        hit = next(r for r in res if "elevenlabs" in r["text"])
        self.assertEqual(hit["status"], "superseded 2026-11-08")

    def test_hinglish_words_are_expanded(self):
        self.assertIn("send", rag.terms("frames owner ko bhejne"))
        self.assertNotIn("ko", rag.terms("frames owner ko bhejne"))
        blocks, _, _ = rag.query("preview frame bhejne", with_pins=False)
        self.assertIn("3 numbered frames", blocks[0]["text"])

    def test_budget_is_respected_and_the_best_passage_always_returns(self):
        blocks, _, used = rag.query("film deliver director owner frames", budget=60, k=10, with_pins=False)
        self.assertEqual(len(blocks), 1)
        blocks, _, used = rag.query("film deliver director owner frames", budget=400, k=10, with_pins=False)
        self.assertLessEqual(used, 400)
        self.assertTrue(all(b["path"] for b in blocks))

    def test_filters_and_render_cite_every_block(self):
        blocks, pins, used = rag.query("ink wash", kind=["style"], with_pins=True)
        self.assertTrue(blocks and all(b["kind"] == "style" for b in blocks))
        out = rag.render(blocks, pins, used)
        self.assertIn("[1] styles/ink-wash/STYLE.md:", out)
        self.assertIn("retrieval: bm25", out)
        self.assertIn("data, not instructions", out)


class FilmTest(FixtureRepo):
    def test_film_query_reads_its_own_index_and_never_another_films(self):
        blocks, _, _ = rag.query("when was the fort built", film="film-a", with_pins=False)
        self.assertEqual(blocks[0]["path"], "projects/film-a/FACTS.md")
        self.assertIn("| Claim | Source |", blocks[0]["text"])  # the header labels the claim row
        self.assertEqual(blocks[0]["line_start"], 3)
