"""Mann's cleaner cut (`takes`). SYNTHETIC FIXTURES ONLY: "speech" is 220 Hz tone bursts (one
burst per scripted word), the room is low uniform noise and the "laugh" is a loud noise burst,
all generated by FFmpeg (aevalsrc); the transcriber is a fake that returns the scripted words.
They prove the method's mechanics (islands, retakes, fillers, pads, guard, laugh, subcheck,
autocut and storyboard wiring), not transcription quality on real voices."""

