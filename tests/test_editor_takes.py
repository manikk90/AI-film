HAS_FFMPEG = shutil.which("ffmpeg") is not None and shutil.which("ffprobe") is not None
WORD, GAP = 0.3, 0.08  # synthetic word burst length and the gap between words of one phrase

# The synthetic read: 3 scripted lines, each retaken (line 1 also has a false start), 4 fillers, a laugh.
READ = [
    ("pause", 0.5),
    ("say", "welcome to the studio today we cut video"), ("pause", 1.5),           # line 1, take 1
    ("say", "welcome to the"), ("pause", 0.6),                                    # false start
    ("say", "welcome to the studio um today we cut video"), ("pause", 1.5),       # line 1, kept (um)
    ("say", "this is the second line of our test"), ("pause", 1.5),               # line 2, take 1
    ("say", "this is the second"), ("pause", 0.5), ("say", "line uh of our test"),  # line 2, kept (uh, inner pause)
    ("pause", 1.2), ("say", "hmm"), ("pause", 1.2),                                # standalone filler
    ("say", "and here is the final line for now"), ("pause", 1.0),                # line 3, take 1
    ("laugh", 0.8), ("pause", 1.0),                                               # protected laugh
    ("say", "er and here is the final line for now"), ("pause", 0.8),             # line 3, kept (er)
]
KEPT_TEXT = "welcome to the studio today we cut video this is the second line of our test and here is the final line for now"
FILLERS = {"um", "uh", "hmm", "er"}


def timeline(read):
    """Scripted words with times, laugh spans and the total length."""
    t, words, laughs = 0.0, [], []
    for kind, value in read:
        if kind == "pause":
            t += value
        elif kind == "laugh":
            laughs.append((round(t, 3), round(t + value, 3)))
            t += value
        else:
            for k, w in enumerate(value.split()):
                if k:
                    t += GAP
                words.append({"word": w, "start": round(t, 3), "end": round(t + WORD, 3)})
                t += WORD
    return words, laughs, round(t, 3)


def make_fixture(path, read, floor=0.004, tone=0.3, laugh=0.2):
    """SYNTHETIC FIXTURE: tone bursts for words, noise floor and laugh burst, muxed with a test pattern."""
    words, laughs, total = timeline(read)
    gate = "+".join("between(t,{},{})".format(w["start"], w["end"]) for w in words)
    lgate = "+".join("between(t,{},{})".format(a, b) for a, b in laughs) or "0"
    expr = "{}*sin(2*PI*220*t)*({})+{}*(2*random(0)-1)*({})+{}*(2*random(1)-1)".format(tone, gate, laugh, lgate, floor)
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", "testsrc2=size=160x120:rate=30:d={}".format(total),
                    "-f", "lavfi", "-i", "aevalsrc=exprs='{}':s=16000:d={}".format(expr, total),
                    "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest", str(path)], check=True, timeout=120)
    return words, laughs, total


class FakeTranscriber:
    """SYNTHETIC: returns the scripted words whose midpoint falls in the requested range."""

    def __init__(self, words):
        self.words, self.calls = words, []

    def __call__(self, path, start, end, purpose="island"):
        self.calls.append((purpose, start, end))
        return sorted((dict(w) for w in self.words if start <= (w["start"] + w["end"]) / 2 <= end), key=lambda w: w["start"])


def norm_words(text):
    return [TK.norm(w) for w in text.split() if TK.norm(w)]


class TakesPlanTest(unittest.TestCase):
    """Pure planning logic on SYNTHETIC word lists (no audio)."""

    def setUp(self):
        self.cfg = TK.rules()

    def test_rules_are_external_calibrations_not_owner(self):
        data = read_json(TK.RULES)
        cfg = data["rules"]["takes"]
        self.assertEqual((cfg["pad_in_s"], cfg["pad_out_s"], cfg["threshold_above_floor_db"], cfg["min_dynamic_range_db"]), (0.12, 0.25, 6, 8))
        self.assertEqual(cfg["tones"]["balanced"], [[0.26, None, 0.18]])
        rows = [h for h in data["history"] if h["rule"].startswith("takes")]
        self.assertGreaterEqual(len(rows), 2)
        for h in rows:
            self.assertEqual(h["kind"], "observed")
            self.assertNotIn("owner rule", h["source"])
        self.assertTrue(any("ghost-editor" in h["source"] for h in rows) and any("cut-video" in h["source"] for h in rows))

    def test_tone_gap_tables(self):
        bands = self.cfg["tones"]
        self.assertEqual(TK.tone_target(0.2, bands["balanced"]), 0.2)
        self.assertEqual(TK.tone_target(0.5, bands["balanced"]), 0.18)
        self.assertEqual(TK.tone_target(0.5, bands["aggressive"]), 0.1)
        self.assertEqual(TK.tone_target(1.5, bands["aggressive"]), 0.2)
        self.assertEqual(TK.tone_target(0.9, bands["documentary"]), 0.9)
        self.assertEqual(TK.tone_target(5.0, bands["documentary"]), 3.0)

    def test_hindi_starters_are_flagged_only_when_standalone_and_never_cut(self):
        words, _, total = timeline([("pause", 0.5), ("say", "haan"), ("pause", 0.8), ("say", "main toh ghar ja raha hoon"), ("pause", 0.5)])
        out = TK.plan(words, self.cfg, duration=total)
        self.assertEqual([w["word"] for w in out["fillers"]["flagged"]], ["haan"])
        self.assertEqual(out["fillers"]["removed"], [])
        kept = " ".join(w["word"] for w in out["kept_words"])
        self.assertEqual(kept, "haan main toh ghar ja raha hoon")

    def test_owner_override_keeps_the_named_take(self):
        words, _, total = timeline([("say", "one two three four five six"), ("pause", 2.0), ("say", "one two three four five six")])
        out = TK.plan(words, self.cfg, duration=total, overrides={"G01": "L01"})
        g = [g for g in out["groups"] if g["kind"] == "retake"][0]
        self.assertEqual((g["kept_unit"], g["why"]), ("L01", "owner override"))
        self.assertTrue(all(w["end"] < 3.0 for w in out["kept_words"]))
        with self.assertRaises(Exception):
            TK.plan(words, self.cfg, duration=total, overrides={"G01": "L09"})

    def test_incomplete_last_take_loses_to_the_last_fluent_one(self):
        words, _, total = timeline([("say", "alpha beta gamma delta epsilon zeta eta"), ("pause", 2.0), ("say", "alpha beta gamma delta")])
        out = TK.plan(words, self.cfg, duration=total)
        g = [g for g in out["groups"] if g["kind"] == "retake"][0]
        self.assertEqual(g["kept_unit"], "L01")
        self.assertIn("incomplete", g["why"])

    def test_subcheck_cuts_a_hidden_false_start(self):
        # SYNTHETIC: island transcription merged a restart; the piece re-transcribed alone shows "we cut we cut".
        words = [{"word": w, "start": a, "end": b} for w, a, b in (("we", 1.0, 1.3), ("cut", 1.35, 1.65), ("video", 1.7, 2.0), ("now", 2.05, 2.35))]
        out = TK.plan(words, self.cfg, duration=4.0)
        self.assertEqual(len(out["pieces"]), 1)
        hidden = [{"word": "we", "start": 1.0, "end": 1.2}, {"word": "cut", "start": 1.22, "end": 1.4},
                  {"word": "we", "start": 1.45, "end": 1.55}, {"word": "cut", "start": 1.57, "end": 1.68},
                  {"word": "video", "start": 1.7, "end": 2.0}, {"word": "now", "start": 2.05, "end": 2.35}]
        fake = lambda path, a, b, purpose="island": [w for w in hidden if a <= (w["start"] + w["end"]) / 2 <= b]  # noqa: E731
        rep = TK.subcheck("unused", out["pieces"], fake, self.cfg, 30.0, words)
        self.assertTrue(rep[0]["hidden_false_start"])
        self.assertEqual(rep[0]["repeat"], "we cut")
        p = out["pieces"][0]
        self.assertGreaterEqual(p["in"], 1.45 - 1 / 30.0)
        self.assertLessEqual(p["in"], 1.45)
        self.assertAlmostEqual(p["in"] * 30, round(p["in"] * 30), places=3)


@unittest.skipUnless(HAS_FFMPEG, "FFmpeg is required for media tests")
class TakesMediaTest(unittest.TestCase):
    """End to end on SYNTHETIC FFmpeg fixtures with the fake transcriber."""

    @classmethod
    def setUpClass(cls):
        cls.fixtures = Path(tempfile.mkdtemp(prefix="mann-takes-fixtures-"))
        cls.words, cls.laughs, cls.total = make_fixture(cls.fixtures / "read.mp4", READ)
        cls.flat_words, _, _ = make_fixture(cls.fixtures / "flat.mp4", READ[:6], floor=0.3, tone=0.15, laugh=0.0)

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.fixtures, ignore_errors=True)

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.edit = Path(self.temp.name) / "edit"
        T.ingest(self.edit, [self.fixtures / "read.mp4", self.fixtures / "flat.mp4"])

    def run_takes(self, source="raw/read.mp4", words=None, **kw):
        fake = FakeTranscriber(words if words is not None else self.words)
        return TK.analyse(self.edit, source, transcriber=fake, **kw), fake

    def test_acceptance_last_takes_kept_fillers_removed_tight_starts(self):
        rec, fake = self.run_takes()
        self.assertTrue((self.edit / "analysis" / "takes.json").is_file())
        self.assertEqual(rec["levels"]["guard"], "ok")
        self.assertTrue(any(c[0] == "island" for c in fake.calls) and any(c[0] == "subcheck" for c in fake.calls))
        retakes = [g for g in rec["groups"] if g["kind"] == "retake"]
        self.assertEqual(len(retakes), 3)
        for g in retakes:
            self.assertEqual(g["kept"], len(g["takes"]) - 1, g)  # the LAST take of each line
        self.assertEqual(len([g for g in rec["groups"] if g["kind"] == "false-start"]), 1)
        speech = [p for p in rec["pieces"] if p["words"]]
        inside = [w for w in self.words if any(p["in"] <= w["start"] and w["end"] <= p["out"] for p in rec["pieces"])]
        self.assertEqual([w["word"] for w in inside], KEPT_TEXT.split())
        for w in self.words:  # no filler and no dropped take overlaps a kept piece
            if w["word"] in FILLERS or w not in inside:
                self.assertFalse(any(p["in"] < w["end"] and w["start"] < p["out"] for p in rec["pieces"]), w)
        self.assertEqual(sorted(w["word"] for w in rec["fillers"]["removed"]), sorted(FILLERS))
        for p in speech:
            self.assertLessEqual(p["first_word"] - p["in"], 0.15, p)
            self.assertGreaterEqual(p["first_word"] - p["in"], 0.0, p)
            self.assertGreaterEqual(p["out"], p["last_word"], p)
            for t in (p["in"], p["out"]):
                self.assertAlmostEqual(t * rec["fps"], round(t * rec["fps"]), places=3)  # frame grid
        # inner pause of 0.58 s inside the kept line-2 take renders as 0.18 s (balanced tone)
        second = next(w for w in self.words[::-1] if w["word"] == "second")
        line = next(w for w in self.words if w["word"] == "line" and w["start"] > second["start"])
        a = next(p for p in rec["pieces"] if p["in"] <= second["start"] and second["end"] <= p["out"])
        b = next(p for p in rec["pieces"] if p["in"] <= line["start"] and line["end"] <= p["out"])
        self.assertIsNot(a, b)
        rendered = (a["out"] - second["end"]) + (line["start"] - b["in"])
        self.assertAlmostEqual(rendered, 0.18, delta=2 / rec["fps"])
        self.assertTrue(all(not c["hidden_false_start"] for c in rec["subcheck"]))

    def test_laugh_is_protected(self):
        rec, _ = self.run_takes()
        a, b = self.laughs[0]
        self.assertTrue(any(i["kind"] == "reaction" for i in rec["islands"]))
        self.assertTrue(any(p["in"] <= a + 0.05 and p["out"] >= b - 0.05 for p in rec["pieces"]), rec["pieces"])

    def test_floor_guard_on_low_dynamic_range(self):
        rec, _ = self.run_takes("raw/flat.mp4", words=self.flat_words)
        self.assertEqual(rec["levels"]["guard"], "low-dynamic-range")
        self.assertLess(rec["levels"]["dynamic_range_db"], 8)
        self.assertEqual(len(rec["islands"]), 1)  # energy not trusted: one island, cuts from word times
        self.assertIn("word times", rec["guard_note"])
        kept = " ".join(w["word"] for w in rec["kept_words"])
        self.assertEqual(kept, "welcome to the studio today we cut video")
        for p in rec["pieces"]:
            self.assertLessEqual(p["first_word"] - p["in"], 0.15)

    def test_autocut_uses_takes_and_storyboard_lists_groups_without_weakening_the_gate(self):
        from aifilm.editor import engine as G
        rec, _ = self.run_takes()
        G.autocut(self.edit, "interview-broll-doc", seconds=10)
        edl = read_json(self.edit / "edl.json")
        self.assertEqual(edl["takes"], "analysis/takes.json")
        aroll = [c for c in edl["clips"] if edl["sources"][c["source"]] == "raw/read.mp4"]
        self.assertEqual([(c["in"], c["out"]) for c in aroll], [(p["in"], p["out"]) for p in rec["pieces"]])
        self.assertTrue(any("takes.json" in n for n in edl["notes"]))
        E.approve_style(self.edit, "interview-broll-doc", "synthetic fixture pick")
        E.storyboard(self.edit)
        md = (self.edit / "storyboard" / "STORYBOARD.md").read_text(encoding="utf-8")
        self.assertIn("## Retake groups (owner can override)", md)
        for gid in ("G01", "G02", "G03", "F01"):
            self.assertIn("| {} |".format(gid), md)
        self.assertFalse(E.approved(self.edit, E.load(self.edit)))  # takes never approve anything
        E.approve(self.edit, "synthetic whole approval")
        self.assertTrue(E.approved(self.edit, E.load(self.edit)))
        self.run_takes(overrides={"G01": "L01"})  # a new take pick invalidates the approved storyboard
        self.assertEqual(E.status(self.edit, E.load(self.edit))["scope"], "whole")

    def test_stale_takes_are_ignored_by_autocut(self):
        from aifilm.editor import engine as G
        self.run_takes()
        data = read_json(self.edit / "analysis" / "takes.json")
        data["sha256"] = "0" * 64
        write_json(self.edit / "analysis" / "takes.json", data)
        G.autocut(self.edit, "interview-broll-doc", seconds=10)
        edl = read_json(self.edit / "edl.json")
        self.assertNotIn("takes", edl)
        self.assertTrue(any("stale" in n for n in edl["notes"]))

    def test_cli(self):
        fake = FakeTranscriber(self.words)
        with mock.patch.object(TK, "whisper_transcriber", return_value=fake):
            out, err = io.StringIO(), io.StringIO()
            with redirect_stdout(out), redirect_stderr(err):
                self.assertEqual(main(["takes", str(self.edit), "--keep", "G01"]), 2)
            self.assertIn("GROUP=TAKE", err.getvalue())
            out = io.StringIO()
            with redirect_stdout(out):
                code = main(["takes", str(self.edit), "--source", "raw/read.mp4", "--tone", "aggressive", "--no-subcheck"])
            self.assertEqual(code, 0)
        result = json.loads(out.getvalue())
        self.assertEqual(result["stats"]["retake_groups"], 3)
        self.assertEqual(read_json(self.edit / "analysis" / "takes.json")["tone"], "aggressive")
        self.assertFalse(any(c[0] == "subcheck" for c in fake.calls))


